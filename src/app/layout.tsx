import type { Metadata } from "next";
import { cookies, headers } from "next/headers";
import { connection } from "next/server";
import "@fontsource-variable/ibm-plex-sans";
import "@fontsource-variable/space-grotesk";
import "@fontsource/ibm-plex-mono";
import "./globals.css";
import { ZodCspProvider } from "@/components/zod-csp-provider";
import { ThemeProvider, themeBootstrapScript, type Theme } from "@/components/settings/theme-provider";

export const metadata: Metadata = {
  title: { default: "Rota CRM", template: "%s · Rota CRM" },
  description: "Relacionamentos bem cuidados, negócios em movimento.",
};

export default async function RootLayout({ children }: Readonly<{ children: React.ReactNode }>) {

  // A nonce-based CSP needs request-time rendering; a build-time static shell
  // cannot receive the per-request nonce generated by proxy.ts.
  await connection();

  const [cookieStore, requestHeaders] = await Promise.all([cookies(), headers()]);
  const preference = cookieStore.get("rota-theme")?.value;
  const theme: Theme = preference === "dark" ? "dark" : "light";
  const nonce = requestHeaders.get("x-nonce") ?? undefined;

  return <>
          <html lang="pt-BR" data-theme={theme} suppressHydrationWarning>
            <head>
              <script
               nonce={nonce} 
               dangerouslySetInnerHTML={{ __html: themeBootstrapScript }} 
              />
            </head>

            <body>
              <ThemeProvider initialTheme={theme}>
                <ZodCspProvider>{children}</ZodCspProvider>
              </ThemeProvider>
            </body>
          </html>
        </>
  
}
